function display(
  name: string,
  manufacturer: string,
  tags: string[] = [],
): DisplayMetadata {
  return {
    displayName: name,
    description: name,
    manufacturerLabel: manufacturer,
    categoryLabels: tags,
    thumbnailKey: null,
    tags,
  };
}

function rev(
  componentId: string,
  revision: string,
  partial: Omit<
    ComponentRevision,
    'componentId' | 'revisionId' | 'schemaVersion' | 'source' | 'releaseStatus'
  >,
): ComponentRevision {
  return {
    componentId: asComponentId(componentId),
    revisionId: asComponentRevisionId(revision),
    source: 'official',
    releaseStatus: 'published',
    schemaVersion: '1.1.0',
    ...partial,
  };
}


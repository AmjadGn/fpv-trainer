export const OFFICIAL_CATALOG_RELEASE: CatalogRelease = {
  releaseId: asCatalogReleaseId('official-catalog-1.1.0'),
  version: '1.1.0',
  componentRevisionIds: OFFICIAL_COMPONENT_REVISIONS.map((r) => r.revisionId),
  publishedAtIso: null,
  label: 'Official Catalog v1.1.0',
};

export function buildOfficialCatalogSnapshot(): ComponentCatalogSnapshot {
  const revisions = new Map<ComponentRevisionId, ComponentRevision>();
  for (const r of OFFICIAL_COMPONENT_REVISIONS) {
    revisions.set(r.revisionId, r);
  }
  return { release: OFFICIAL_CATALOG_RELEASE, revisions };
}

export function getRevision(
  snapshot: ComponentCatalogSnapshot,
  revisionId: ComponentRevisionId | string,
): ComponentRevision | undefined {
  return snapshot.revisions.get(revisionId as ComponentRevisionId);
}
